  assert.match(gameStageSource, /!isTurnNoticeOpen\.value/)
  assert.match(gameStageSource, /areAutoNoticesSuppressed/)
  assert.match(gameStageSource, /isSkipSettlementActive/)
  assert.match(gameStageSource, /playSkippedRoundSettlement/)
  assert.match(gameStageSource, /const protectedPlayerIds = computed/)

  assert.match(settingsSource, /@media \(max-width: 760px\) \{[\s\S]*\.settings-dialog \{[\s\S]*overflow: hidden;/)
  assert.match(settingsSource, /@media \(max-width: 760px\) \{[\s\S]*\.settings-header \{[\s\S]*min-height: 48px;/)
